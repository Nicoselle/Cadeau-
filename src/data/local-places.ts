import type { Place } from "@/types/local";

function be(name: string, province: string): Place {
  return {
    slug: name
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase()
      .replace(/['’]/g, "")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, ""),
    name,
    country: "BE",
    province,
  };
}

function nl(name: string, province: string): Place {
  return { ...be(name, province), country: "NL" };
}

